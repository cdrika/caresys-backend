const {chromium}=require(process.env.CARESYS_NODE_MODULES+'/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1100,height:1000}});
  const page=await context.newPage();const errors=[];
  context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('https://localhost:8444/mobile-enrollment');
  await page.locator('[name=email]').fill('candidate@caresys.test');
  await page.locator('[name=password]').fill('CareSysDemo!2026');
  await Promise.all([page.waitForURL('**/mobile-enrollment'),page.getByRole('button',{name:/Sign in/}).click()]);
  assert.equal(await page.locator('[name=user_code]').getAttribute('placeholder'),'Enter your device code');
  await page.locator('[name=user_code]').fill('A1B2-C3D4-E5F6');
  await page.getByRole('button',{name:'Review device'}).click();
  await page.waitForURL('**/mobile-enrollment/review');
  assert.match(await page.getByRole('alert').innerText(),/Request a new code on your device/);
  const [device]=await Promise.all([context.waitForEvent('page'),page.getByRole('link',{name:/Open local test device/}).click()]);
  await device.waitForLoadState();
  await device.locator('#device-name').fill('QA interactive test device');
  await device.getByRole('button',{name:'Create pairing code'}).click();
  await device.locator('#pairing').waitFor({state:'visible'});
  const code=await device.locator('#pairing-code').inputValue();
  assert.match(code,/^[A-F0-9]{4}(-[A-F0-9]{4}){2}$/);
  assert.notEqual(code,'A1B2-C3D4-E5F6');
  await page.locator('[name=user_code]').fill(code);
  await page.getByRole('button',{name:'Review device'}).click();
  await page.waitForURL('**/mobile-enrollment/review');
  assert.equal(await page.locator('.pairing-device h2').innerText(),'QA interactive test device');
  await page.locator('[name=password]').fill('CareSysDemo!2026');
  await page.locator('[name=confirm]').check();
  await page.getByRole('button',{name:'Approve this device'}).click();
  await device.getByRole('status').filter({hasText:'Connected.'}).waitFor({timeout:20000});
  assert.deepEqual(await device.evaluate(()=>({local:localStorage.length,session:sessionStorage.length})),{local:0,session:0});
  fs.mkdirSync('build/qa/mobile-pairing',{recursive:true});
  await device.screenshot({path:'build/qa/mobile-pairing/test-device-connected.png',fullPage:true});
  await device.getByRole('button',{name:'Disconnect test device'}).click();
  await device.getByRole('status').filter({hasText:'Disconnected.'}).waitFor();
  await page.goto('https://localhost:8444/mobile-enrollment');
  assert.equal(await page.locator('.pairing-session').filter({hasText:'QA interactive test device'}).count(),0);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.screenshot({path:'build/qa/mobile-pairing/recovery-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: example-code recovery, real-code generation, browser approval, isolated API verification, memory-only credentials, disconnect, mobile layout.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
